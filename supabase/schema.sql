-- Daily Games Board: blank standalone database
-- Run once in the SQL Editor of a NEW Supabase project.

create table public.players (
  id text primary key,
  name text not null check (char_length(name) between 1 and 40),
  created_at timestamptz not null default now()
);

create table public.results (
  id bigint generated by default as identity primary key,
  day date not null,
  player text not null references public.players(id) on update cascade on delete cascade,
  game text not null check (game in ('wordle', 'perceptle', 'krillion', 'maptap', 'sizeitup')),
  score integer not null,
  display text not null,
  puzzle integer,
  rounds jsonb,
  grid text,
  raw text,
  updated_at timestamptz not null default now(),
  constraint results_one_game_per_player_per_day unique (day, player, game)
);

create index results_day_idx on public.results (day desc);
create index results_game_day_idx on public.results (game, day desc);

alter table public.players enable row level security;
alter table public.results enable row level security;

revoke all on table public.players, public.results from anon, authenticated;
revoke all on sequence public.results_id_seq from anon, authenticated;

